// Copies the lucide glyphs the app renders out of the app's own node_modules
// into src/icons.ts, so the phone in the video draws the same icons as the
// app. Run with `npm run icons` after changing NAMES.
const fs = require("fs");
const path = require("path");

const NAMES = [
  "battery-full",
  "bell",
  "chevron-right",
  "cloud-rain",
  "cloud-sun",
  "ellipsis-vertical",
  "heart-pulse",
  "hospital",
  "map-pin",
  "mountain",
  "navigation",
  "send",
  "shield",
  "signal",
  "thermometer",
  "wifi",
  "wind",
];

const dir = path.join(
  __dirname,
  "../../node_modules/lucide-react-native/dist/esm/icons",
);

const icons = {};
for (const name of NAMES) {
  const src = fs.readFileSync(path.join(dir, `${name}.mjs`), "utf8");
  const body = src.match(
    /createLucideIcon\("[^"]+",\s*([\s\S]*?)\);\s*\n\s*export/,
  )[1];
  icons[name] = Function(`return ${body}`)()
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}

fs.writeFileSync(
  path.join(__dirname, "src/icons.ts"),
  `// Generated by extract-icons.cjs from lucide-react-native (ISC). Do not edit.\n` +
    `export const ICONS = ${JSON.stringify(icons, null, 2)} as const;\n\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log(`wrote ${NAMES.length} icons`);
